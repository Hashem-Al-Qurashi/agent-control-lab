"""Generates docs/RESULTS.md from the run that verifies it.

Deliberately not written by hand. Every number in the report comes from the same
execution that asserts it, so the document cannot drift from the code -- the
failure mode where a README claims a result the repo no longer produces.

It asserts the expected verdict for every schedule as it goes, so this is a test
first and a generator second. If a verdict changes, this fails rather than
quietly publishing the new number.
"""

import pathlib
from decimal import Decimal

import pytest

from apps.reconciliation.worker import reconcile
from oracle.invariants import Verdict
from schedules.runner import (
    assert_actors_succeeded,
    assert_schedule_executed,
    expected_release_order,
    load,
    run_schedule,
)

REPO = pathlib.Path(__file__).resolve().parents[2]

# (schedule, expected verdict, role, actors_expected_to_be_refused)
#
# The last field matters: in S6 a refusal IS the result. Treating every actor
# error as a broken run would reject the one schedule whose point is that
# authorization stops the action.
EXPECTED = [
    ("P1", Verdict.CLEAN, "Sequential. Proves the oracle is not trigger-happy.", False),
    ("P2", Verdict.VIOLATION, "Concurrent read-check-write race. Positive control.", False),
    ("P0", Verdict.CLEAN, "P2's interleaving with a reservation. Locates the fault in the interface.", False),
    ("P3", Verdict.CLEAN, "Lost ACK, keyed retry. Idempotency is orthogonal to the aggregate.", False),
    ("S1", Verdict.VIOLATION, "Strictly sequential, stale read model. Sequencing does not fix it.", False),
    ("S1C", Verdict.CLEAN, "S1 with the projection caught up. Isolates the variable.", False),
    ("S1H", Verdict.CLEAN, "S1 with a reservation. Coordination fixes staleness too.", False),
    ("S3", Verdict.VIOLATION, "Partial catch-up. The exposure tracks the lag.", False),
    ("S4", Verdict.CLEAN, "Reversed apply order. Rules out ordering as the cause.", False),
    ("S5", Verdict.CLEAN, "At-least-once redelivery. The projection must not inflate.", False),
    ("S6", Verdict.CLEAN, "Above-threshold without approval. Authorization is not decorative.", True),
]


def test_generate_results_report(clean_state):
    from apps.billing.db import truncate_all as billing_truncate
    from apps.control.db import truncate_all as control_truncate
    from apps.crm.db import truncate_all as crm_truncate
    from apps.ledger.db import truncate_all as ledger_truncate

    rows = []
    for schedule_id, expected, role, expect_refusals in EXPECTED:
        # Between schedules, not merely at the start. State from an earlier run
        # otherwise reaches the next one -- which is how the first version of
        # this generator published numbers from partially-failed runs.
        billing_truncate()
        ledger_truncate()
        control_truncate()
        crm_truncate()

        outcome = run_schedule(schedule_id, clean_state)
        result = outcome.result

        # A run whose actors failed is not evidence of anything -- unless the
        # refusal is the result, as in S6.
        if expect_refusals:
            refused = [o for o in outcome.actor_outcomes if o[0] == "error"]
            assert refused, f"{schedule_id} expected refusals and got none"
            assert all("403" in str(o[2]) for o in refused), refused
        else:
            assert_actors_succeeded(outcome)
        assert_schedule_executed(outcome, expected_release_order(schedule_id))
        assert outcome.parked_waiters == [], (
            f"{schedule_id} stranded a waiter: {outcome.parked_waiters}"
        )

        assert result.verdict is expected, (
            f"{schedule_id} returned {result.verdict.value}, expected "
            f"{expected.value} -- the report must not publish a number the code "
            "no longer produces"
        )

        report = reconcile(f"case-{schedule_id.lower()}")
        rows.append(
            {
                "id": schedule_id,
                "verdict": result.verdict.value,
                "committed": result.committed_total,
                "overage": result.realized_overage,
                "steps": len(outcome.release_order),
                "actors": len(load(schedule_id)["actors"]),
                "monitoring": "clean" if report.clean else f"{len(report.findings)} finding(s)",
                "role": role,
            }
        )

    violations = [r for r in rows if r["verdict"] == "VIOLATION"]
    silent = [r for r in violations if r["monitoring"] == "clean"]

    lines = [
        "# Results",
        "",
        "> Generated by `tests/schedules/test_results_report.py`, which asserts "
        "every verdict below as it measures it. Not written by hand.",
        "",
        f"**{len(rows)} schedules · {len(violations)} produce a violation · "
        f"{len(silent)} of those are invisible to ordinary monitoring.**",
        "",
        "| Schedule | Verdict | Committed | Overage | Actors | Steps | Ordinary monitoring | Role |",
        "|---|---|---:|---:|---:|---:|---|---|",
    ]
    for r in rows:
        lines.append(
            f"| **{r['id']}** | {r['verdict']} | {r['committed']} | "
            f"{r['overage']} | {r['actors']} | {r['steps']} | {r['monitoring']} | "
            f"{r['role']} |"
        )

    lines += [
        "",
        "### Reading the monitoring column",
        "",
        "A finding is not the same as detecting the breach. The reconciler looks "
        "for generic operational anomalies -- projection lag, drift, duplicate "
        "keys, orphans -- and is deliberately **not** told the aggregate ceiling, "
        "because giving the baseline that rule would make the silent-failure "
        "result circular.",
        "",
        "P1, P2, P0 and P3 have no projector actor, so their events are never "
        "consumed and the reconciler correctly reports lag. That lag is unrelated "
        "to whether the money is right.",
        "",
        "**S1 and S3 are the ones that matter.** Their projections caught up, so "
        "there is no lag to report, and the reconciler is fully clean while the "
        "business state is wrong by $100. That is the silent failure, measured.",
        "",
        "## What the violations have in common",
        "",
        "Every violating schedule shares four properties. Each action was:",
        "",
        "- **authenticated** with a signed token the agent cannot forge or widen",
        "- **authorized** by a policy the agent does not evaluate",
        "- **idempotent**, keyed so a retry produces one effect",
        "- **individually correct** given everything the actor could observe",
        "",
        "And in every case, ordinary monitoring reported nothing.",
        "",
        "## What separates P2 from S1",
        "",
        "P2 is a timing race: both actors read before either wrote. Sequencing "
        "them fixes it, which is what P1 shows.",
        "",
        "S1 is not a race. B reads **strictly after** A has fully committed and "
        "is wrong anyway, because the view it was given had not caught up. "
        "Sequencing does not fix it. S1C shows the only variable is whether the "
        "read model had caught up when consulted.",
        "",
        "S3 rules out the comfortable reading that this needs a completely cold "
        "view: applying one of two pending events still breaches.",
        "",
        "## What fixes both",
        "",
        "P0 and S1H apply the same reservation primitive to the two different "
        "failure modes, and both stay clean. The reason is that the control "
        "service holds **authoritative** state rather than a derived view — S1H "
        "asserts B's projection was exactly as stale as in S1 and the outcome "
        "was still correct.",
        "",
        "So the remedy is not a faster projection. A faster projection is still "
        "a projection.",
        "",
        "## What this does not claim",
        "",
        "Read-then-write across uncoordinated systems is textbook and predates "
        "this repo by decades. Nothing here is presented as a discovery. What is "
        "measured is the **combination**: that these failures survive proper "
        "authentication, proper authorization, idempotency, strict sequencing, "
        "and competent monitoring simultaneously.",
        "",
        "Scope: two failure modes at one level of concurrency, in a harness whose "
        "schedules are deterministic by construction. Not a frequency estimate "
        "for any production system.",
        "",
    ]

    (REPO / "docs" / "RESULTS.md").write_text("\n".join(lines))

    assert silent, "no violation was invisible to monitoring -- H2 does not hold"
