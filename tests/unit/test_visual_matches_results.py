"""The published visualisation must agree with the measured results.

The page is hand-authored from the schedules. That makes it exactly the kind of
artifact this repo keeps catching: a confident-looking claim with nothing tying
it to reality, which stays wrong silently after a schedule changes.

RESULTS.md is generated by the run that asserts it. This pins the page to it.
"""

import pathlib
import re

import pytest

REPO = pathlib.Path(__file__).resolve().parents[2]
PAGE = REPO / "docs" / "visual" / "diligent-agent.html"
RESULTS = REPO / "docs" / "RESULTS.md"

SHOWN = ["P2", "S1", "P0", "S1H"]


def _measured() -> dict[str, tuple[str, str]]:
    """schedule -> (verdict, committed total) straight from RESULTS.md."""
    rows = {}
    for line in RESULTS.read_text().splitlines():
        m = re.match(r"\|\s*\*\*(\w+)\*\*\s*\|\s*(VIOLATION|CLEAN)\s*\|\s*([\d.]+)", line)
        if m:
            rows[m.group(1)] = (m.group(2).lower(), m.group(3))
    return rows


def _page_block(schedule: str) -> str:
    text = PAGE.read_text()
    start = text.index(f'id:"{schedule}"')
    end = text.index("]}", start)
    return text[start:end]


def test_the_page_shows_only_schedules_that_exist():
    measured = _measured()
    missing = [s for s in SHOWN if s not in measured]

    assert not missing, f"the page walks through schedules absent from RESULTS.md: {missing}"


@pytest.mark.parametrize("schedule", SHOWN)
def test_the_page_ends_on_the_measured_verdict(schedule):
    verdict, _ = _measured()[schedule]
    block = _page_block(schedule)

    found = re.search(r'verdict:"(\w+)"', block)
    assert found, f"{schedule} declares no verdict in the page"
    assert found.group(1) == verdict, (
        f"the page shows {schedule} ending {found.group(1)}, "
        f"but the run measured {verdict}"
    )


@pytest.mark.parametrize("schedule", SHOWN)
def test_the_page_ends_on_the_measured_total(schedule):
    _, total = _measured()[schedule]
    block = _page_block(schedule)

    totals = [int(t) for t in re.findall(r"\bt:(\d+)", block)]
    assert totals, f"{schedule} has no committed totals in the page"
    assert float(totals[-1]) == float(total), (
        f"the page ends {schedule} at {totals[-1]}, but the run measured {total}"
    )


def test_the_ceiling_on_the_page_is_the_one_the_lab_uses():
    ceiling = re.search(r"const CEIL\s*=\s*(\d+)", PAGE.read_text())

    assert ceiling and ceiling.group(1) == "1000"
